#!/bin/bash
#
# build-installer.sh - generates install.sh from the three deployable files:
#   pusula-auto-update, pusula-auto-update.service, pusula-auto-update.timer
#
# Each file is embedded verbatim in a quoted heredoc (cat > ... <<'DELIM'),
# so install.sh writes byte-identical copies. The generator refuses input that
# would not survive a copy/paste (non-ASCII, tabs, CR, missing final newline,
# a line equal to its heredoc delimiter), embeds sha256 sums the installer
# verifies, and finally extracts every heredoc back out of install.sh and
# compares it with its source.
#
# Usage: ./build-installer.sh   (writes install.sh next to this script)

set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/install.sh"
TMP="$OUT.tmp"

# source file | install path variable | install name | heredoc delimiter
FILES=(
  "pusula-auto-update|sbin_dir|pusula-auto-update|PUSULA_AU_UPDATER_EOF_9F3K"
  "pusula-auto-update.service|unit_dir|pusula-auto-update.service|PUSULA_AU_SERVICE_EOF_9F3K"
  "pusula-auto-update.timer|unit_dir|pusula-auto-update.timer|PUSULA_AU_TIMER_EOF_9F3K"
)

fail() {
  echo "build-installer: $*" >&2
  rm -f "$TMP"
  exit 1
}

check_source() {
  local file="$1" delim="$2"
  [ -f "$file" ] || fail "$file is missing"
  [ -s "$file" ] || fail "$file is empty"
  [ "$(tail -c 1 "$file" | od -An -c | tr -d ' ')" = '\n' ] || fail "$file does not end with a newline"
  if LC_ALL=C grep -q -P '[^\x0A\x20-\x7E]' "$file"; then
    fail "$file contains non-ASCII, tab or control characters:
$(LC_ALL=C grep -n -P '[^\x0A\x20-\x7E]' "$file" | head -n 5)"
  fi
  if grep -qx -- "$delim" "$file"; then
    fail "$file contains a line equal to its heredoc delimiter $delim"
  fi
}

emit_header() {
  cat <<'HEADER_EOF'
#!/bin/bash
#
# Pusula auto-update installer.
#
# Paste this whole text into a root shell on the server (Termius is fine) and
# press Return if nothing starts; or copy it there and run:  bash install.sh
#
# It installs /usr/local/sbin/pusula-auto-update plus the systemd units
# pusula-auto-update.service and pusula-auto-update.timer, enables the timer
# (every 15 minutes) and starts the first update under systemd while showing
# its log. An SSH drop or Ctrl-C does not stop that update.
#
# Everything sits inside shell functions and only the last line runs them, so
# a paste that got cut off installs nothing: the shell just waits at a ">"
# prompt (press Ctrl-C). Embedded sha256 sums catch a damaged paste.
#
# Generated by build-installer.sh from the three files. Do not edit by hand.

set +H

pusula_au_commands() {
  cat <<'PUSULA_AU_HELP_EOF_9F3K'
Status:       pusula-auto-update --status
Logs:         journalctl -t pusula-auto-update -n 100 --no-pager
Update now:   pusula-auto-update
Roll back:    pusula-auto-update --rollback
              (previous version + the data backup taken when it was replaced)
Resume:       pusula-auto-update --reset   (after a pause)
Disable:      systemctl disable --now pusula-auto-update.timer
PUSULA_AU_HELP_EOF_9F3K
}

pusula_au_install() {
  local sbin_dir=/usr/local/sbin
  local unit_dir=/etc/systemd/system
  local c rc

  if [ "$(id -u)" -ne 0 ]; then
    echo "ERROR: run this as root (sudo -i first)." >&2
    return 1
  fi
  for c in docker systemctl systemd-run journalctl flock tar gzip sha256sum timeout curl; do
    command -v "$c" >/dev/null 2>&1 || echo "WARNING: '$c' was not found on this server." >&2
  done
  if ! command -v docker-compose >/dev/null 2>&1 && ! docker compose version >/dev/null 2>&1; then
    echo "WARNING: neither docker-compose nor the docker compose plugin was found." >&2
  fi
  mkdir -p "$sbin_dir" "$unit_dir" || return 1
HEADER_EOF
}

emit_file() {
  local src="$1" dir_var="$2" name="$3" delim="$4"
  printf '\n  echo "Writing $%s/%s"\n' "$dir_var" "$name"
  printf '  cat > "$%s/%s.new" <<'"'"'%s'"'"' || return 1\n' "$dir_var" "$name" "$delim"
  cat "$HERE/$src"
  printf '%s\n' "$delim"
}

emit_checks_and_install() {
  local spec src dir_var name delim sum
  printf '\n  if ! printf '"'"'%%s  %%s\\n'"'"' \\\n'
  for spec in "${FILES[@]}"; do
    IFS='|' read -r src dir_var name delim <<< "$spec"
    sum="$(sha256sum "$HERE/$src" | cut -d' ' -f1)"
    printf '      "%s" "$%s/%s.new" \\\n' "$sum" "$dir_var" "$name"
  done
  cat <<'CHECK_EOF'
      | sha256sum -c --quiet; then
    echo "ERROR: checksum mismatch, the pasted text was damaged. Nothing was installed." >&2
    rm -f "$sbin_dir/pusula-auto-update.new" "$unit_dir/pusula-auto-update.service.new" \
      "$unit_dir/pusula-auto-update.timer.new"
    return 1
  fi
  chmod 0755 "$sbin_dir/pusula-auto-update.new" || return 1
  chmod 0644 "$unit_dir/pusula-auto-update.service.new" "$unit_dir/pusula-auto-update.timer.new" || return 1
  # mv swaps the inode, so a run that is executing right now keeps its copy.
  mv -f "$sbin_dir/pusula-auto-update.new" "$sbin_dir/pusula-auto-update" || return 1
  mv -f "$unit_dir/pusula-auto-update.service.new" "$unit_dir/pusula-auto-update.service" || return 1
  mv -f "$unit_dir/pusula-auto-update.timer.new" "$unit_dir/pusula-auto-update.timer" || return 1
  echo "Files installed and verified."

  systemctl daemon-reload || return 1
  # On a running server, enabling the timer may start the first update at
  # once (OnBootSec= already in the past); the updater below then shows that
  # run from its first line instead of starting a second one.
  systemctl enable --now pusula-auto-update.timer || return 1
  echo
  echo "== Pusula auto-update is installed =="
  echo "Every 15 minutes the server checks ghcr.io/ferhat-yasinoglu/pusula:main."
  echo "A failed update rolls itself back; after 2 failures in a row it pauses."
  echo
  pusula_au_commands
  echo
  echo "== First update run (under systemd; Ctrl-C only stops watching) =="
  "$sbin_dir/pusula-auto-update"
  rc=$?
  echo
  case "$rc" in
    0) echo "== First run finished OK ==" ;;
    2) echo "== First run FAILED and the old version is not back: THE SITE MAY BE DOWN. =="
       echo "== The next run (within 15 minutes) tries again. See the log above and: pusula-auto-update --status ==" ;;
    130) echo "== Stopped watching; the first run goes on. Check it with: pusula-auto-update --status ==" ;;
    *) echo "== First run did NOT finish OK (exit $rc). See the log above and: pusula-auto-update --status ==" ;;
  esac
  echo
  echo "== Commands =="
  pusula_au_commands
  return "$rc"
}

pusula_au_install
CHECK_EOF
}

# Prints the body of the heredoc that ends with $1 (from install.sh $2).
extract_heredoc() {
  awk -v d="$1" '
    started && $0 == d { exit }
    started { print }
    index($0, "<<'"'"'" d "'"'"'") { started = 1 }
  ' "$2"
}

main() {
  local spec src dir_var name delim
  for spec in "${FILES[@]}"; do
    IFS='|' read -r src dir_var name delim <<< "$spec"
    check_source "$HERE/$src" "$delim"
  done

  {
    emit_header
    for spec in "${FILES[@]}"; do
      IFS='|' read -r src dir_var name delim <<< "$spec"
      emit_file "$src" "$dir_var" "$name" "$delim"
    done
    emit_checks_and_install
  } > "$TMP"

  bash -n "$TMP" || fail "generated installer has a syntax error"
  for spec in "${FILES[@]}"; do
    IFS='|' read -r src dir_var name delim <<< "$spec"
    cmp -s "$HERE/$src" <(extract_heredoc "$delim" "$TMP") || fail "embedded $src differs from its source"
  done
  if LC_ALL=C grep -q -P '[^\x0A\x20-\x7E]' "$TMP"; then
    fail "generated installer contains non-ASCII, tab or control characters"
  fi
  mv -f "$TMP" "$OUT"
  chmod 0755 "$OUT"
  echo "wrote $OUT ($(wc -c < "$OUT") bytes, $(wc -l < "$OUT") lines); embedded files verified byte-identical"
}

main "$@"
